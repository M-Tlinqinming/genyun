// ── 2 应急组织机构及职责 ──
function organization(ctx: PlanContext): string {
  const org = ctx.input.organization;
  const kinds = new Set(org.groups.map((g) => g.kind));
  const commanderPos = org.commander?.position?.trim() || '总经理';
  const deputyPos = org.deputies.length
    ? [...new Set(org.deputies.map((d) => d.position?.trim() || '副总指挥'))].join('、')
    : MISSING;
  const medicalDuty =
    '事故现场初期急救与伤员检伤分类，与属地医院应急绿色通道对接并组织转运，急救药品器材的管理与补充，对受伤及参与抢险人员的心理应激初步干预';
  const evacuationDuty =
    '事故现场警戒封控与危险区域划定，在岗人员、承包商及外来人员的疏散引导与清点核对，应急通道与厂区交通管制，无关人员的管控与劝离';
  const sources = ['电气', '高温', ...(ctx.hazardous.length ? ['危险化学品'] : []), ...(ctx.scope.dustProcess ? ['粉尘'] : [])].join('、');
  const duty: Record<string, string> = {
    rescue: `现场抢险与初期火灾扑救，被困及受伤人员的搜救、转移与移交，危险源（${sources}等）的紧急处置与隔离，防止事态扩大，配合到场专业救援队伍开展处置`,
    logistics:
      '应急物资、装备、车辆、资金的调配与后勤供应保障，事故现场污染物收集与无害化处置的组织，伤员转运车辆与生活后勤保障，协助现场警戒与外部救援力量的接待引导' +
      (kinds.has('medical') ? '' : `；并负责${medicalDuty}`) +
      (kinds.has('evacuation') ? '' : `；并负责${evacuationDuty}`),
    communication:
      '对内应急指令的上下贯通与传达，对外向政府主管部门、消防、医院、相邻企业的报告与联络，应急通讯设备保障与 24 小时值守，应急过程信息记录及对外信息发布的协助',
    evacuation: evacuationDuty,
    medical: medicalDuty,
  };
  const groups = [
    ...CHAPTER_ORDER.flatMap((k) => org.groups.filter((g) => g.kind === k)),
    ...org.groups.filter((g) => g.kind === 'custom'),
  ];
  const commanderDuties = [
    '负责组织制定应急预案，负责应急救援指挥工作；',
    '负责做好稳定生产秩序和伤亡人员的善后及安抚工作；',
    '负责组织预案的演练，及时对预案进行调整、修订和补充；',
    '当相邻单位发生生产安全事故，或上级相关部门发出生产安全事故信息后，向所辖区域内相关单位通报事故信息及协助救援；',
    '负责启动专项或综合应急救援预案；',
    '配合上级部门进行事故调查处理和生产安全事故信息的上报工作。',
  ];
  const deputyDuties = [
    '负责协助总指挥做好现场抢险救灾工作的紧急组织，向总指挥汇报情况，落实总指挥发布的抢险命令；',
    '负责指挥技术人员，对抢险、抢修作业根据技术规范和实际情况，提供准确可行的抢险方案，并随时向总指挥汇报情况；',
    '负责现场保卫及周边警戒的协调工作，布置善后的现场保护，维护工作秩序，防止意外破坏情况发生；',
    '负责组织、安排好人员和车辆，准备按指挥命令行动；负责预备队的组织及材料、膳食等综合保障，随时准备补充抢险队伍；',
    '总指挥因故不在时，代行使总指挥的职责。',
  ];
  return [
    '# 应急组织机构及职责',
    '## 应急组织机构',
    `${ctx.company}建立「应急指挥部 + 专业应急工作小组」的两级应急组织体系。应急指挥部为本企业应急管理的最高决策与指挥机构，下设若干专业应急工作小组，各小组的人员构成、职责分工与行动任务以工作方案形式纳入本预案附件管理。应急组织实行总指挥负责制，事故发生时按 1.2 响应分级由对应层级统一指挥。`,
    '[[figure:org-chart]]',
    `**${ctx.company}应急救援组织体系图**`,
    '## 应急组织机构构成单位及处置职责',
    '应急指挥部由总指挥、副总指挥及各专业应急工作小组组成，各岗位职务任职及职责如下；成员姓名、联系方式见应急预案编制小组与附件5 有关应急部门、机构或人员的联系方式。',
    '### 总指挥职责',
    `总指挥由本企业${commanderPos}担任（总指挥外出时，由副总指挥或指定代理人代行总指挥职责）；负责应急预案的日常维护、修订，应急器材的配备与维护保养，应急培训与演练等。主要职责：`,
    ...commanderDuties.map((d, i) => `（${i + 1}）${d}`),
    ...(org.deputies.length
      ? [
          '### 副总指挥职责',
          `副总指挥由本企业${deputyPos}担任（副总指挥外出时，由主管负责人或指定代理人代行副总指挥职责），通常兼任现场指挥。主要职责：`,
          ...deputyDuties.map((d, i) => `（${i + 1}）${d}`),
        ]
      : []),
    '### 各应急小组组成和职责',
    '各应急工作小组的完整成员名单、联系方式详见附件5 有关应急部门、机构或人员的联系方式；事故发生时各小组按下列职责及对应专项应急预案 / 现场处置方案的工作方案执行。应急组织成员发生变动时，由安全管理部门在 14 日内调整并更新附件，确保应急组织始终完整有效。各组职责：',
    ...groups.map((g) => `**${g.name}**：负责${duty[g.kind] ?? '本组职责范围内的应急处置工作，服从总指挥统一调度'}。`),
  ].join('\n');
}

// ── 3 应急响应 ──
