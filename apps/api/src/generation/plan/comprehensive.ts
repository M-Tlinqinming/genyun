const CHAPTER_ORDER = ['rescue', 'logistics', 'communication', 'evacuation', 'medical'] as const;

/** 对内发布、通知的渠道：广播、即时通讯群只在资料里有时写 */
function notifyChannels(ctx: PlanContext): string {
  const f = ctx.facts;
  return [...(f.hasPaSystem ? ['应急广播'] : []), ...(f.hasImGroup ? ['企业微信群'] : []), '电话', '车间班前会', '岗位张贴'].join('、');
}

/** 资料里设有应急办公室才写「应急办公室」，否则由总指挥指定专人 */
const officeOf = (ctx: PlanContext) => (ctx.facts.hasEmergencyOffice ? '应急办公室' : '总指挥指定的专人');

export function comprehensiveMarkdown(ctx: PlanContext): string {
  return [scopeAndGrading(ctx), organization(ctx), response(ctx), postDisposal(ctx), guarantee(ctx)].join('\n\n');
}

